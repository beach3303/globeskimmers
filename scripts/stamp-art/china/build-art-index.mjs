#!/usr/bin/env node
// Generates src/lib/stampArtChina.js — how the app finds the China series' art (2026-11-22).
//
//   node scripts/stamp-art/china/build-art-index.mjs
//
// Reads cn-art-index.json (file slug → the database row resolve_rows.py chose), list-2026-11-14.json,
// db-cn-2026-11-22.json (every live China row) and d1-china-stamps.sql (the rows it will insert), and writes:
//   CN_BY_ID  row id → file          every row that IS the place (the chosen row + same-named rows within 10 km)
//   CN_ALIAS  name slug → file       the list name itself (so the 2026-10-04 index can't redirect it) + each row's own name
//   CN_ONLY   file → [row ids]       a row that merely shares the name never borrows the art
//   CN_CC     file → ["CN"]          and nothing outside China does either (West Street, Golden Beach, East Lake …)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "../../..");
const OUT = path.join(ROOT, "src/lib/stampArtChina.js");
const slug = (s) => String(s || "").normalize("NFKD").replace(/[̀-ͯ]/g, "").replace(/\([^)]*\)/g, " ")
  .toLowerCase().replace(/['’]/g, "").replace(/œ/g, "oe").replace(/æ/g, "ae").trim().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
const km = (a, b, c, d) => { const p = Math.PI / 180, x = Math.sin((c - a) * p / 2) ** 2 + Math.cos(a * p) * Math.cos(c * p) * Math.sin((d - b) * p / 2) ** 2; return 12742 * Math.asin(Math.sqrt(x)); };

const index = JSON.parse(fs.readFileSync(path.join(HERE, "cn-art-index.json"), "utf8"));
const list = JSON.parse(fs.readFileSync(path.join(HERE, "list-2026-11-14.json"), "utf8"));
const db = JSON.parse(fs.readFileSync(path.join(HERE, "db-cn-2026-11-22.json"), "utf8"));
const sql = fs.existsSync(path.join(HERE, "d1-china-stamps.sql")) ? fs.readFileSync(path.join(HERE, "d1-china-stamps.sql"), "utf8") : "";
const byId = new Map(db.map((r) => [r.id, r]));
// rows the SQL will insert: id, name, lat, lng
for (const m of sql.matchAll(/INSERT OR IGNORE INTO attractions .*? VALUES \('([^']+)','((?:[^']|'')*)','(?:[^']|'')*',(-?[\d.]+),(-?[\d.]+)/g)) {
  if (!byId.has(m[1])) byId.set(m[1], { id: m[1], name: m[2].replace(/''/g, "'"), lat: +m[3], lng: +m[4], pending: true });
}
const byName = new Map(list.map((x) => [x.file.replace(/\.png$/, ""), x]));

const BY_ID = {}, ALIAS = {}, ONLY = {}, CC = {};
let pendingRows = 0, extraRows = 0;
for (const [file, hit] of Object.entries(index)) {
  const place = byName.get(file); if (!place) continue;
  const row = byId.get(hit.id);
  const ids = new Set([hit.id]);
  if (row?.pending) pendingRows++;
  if (row && row.lat != null) {
    // other live rows that are the same place under the same (or the list's) name, within 10 km
    const names = new Set([slug(place.name), slug(row.name), file]);
    for (const r of db) {
      if (r.id === row.id || r.lat == null || !names.has(slug(r.name))) continue;
      if (km(+row.lat, +row.lng, +r.lat, +r.lng) <= 10) { ids.add(r.id); extraRows++; }
    }
  }
  for (const id of ids) { BY_ID[id] = file; const r = byId.get(id); if (r && slug(r.name) && slug(r.name) !== file) ALIAS[slug(r.name)] = file; }
  if (slug(place.name) !== file) ALIAS[slug(place.name)] = file;
  ALIAS[file] = file;                       // identity: the older generated index must not redirect this name elsewhere
  ONLY[file] = [...ids].sort();
  CC[file] = ["CN"];
}
// an alias must never point two files at once; the file's own name wins
for (const [k, v] of Object.entries(ALIAS)) if (byName.has(k) && k !== v) ALIAS[k] = k;

const fmt = (o, arr) => Object.keys(o).sort().map((k) => `  ${JSON.stringify(k)}: ${arr ? JSON.stringify(o[k]) : JSON.stringify(o[k])},`).join("\n");
const out = `// GENERATED by scripts/stamp-art/china/build-art-index.mjs from scripts/stamp-art/china/cn-art-index.json
// (the founder's China stamp series, 2026-11-22: ${Object.keys(ONLY).length} files). Do not edit by hand — re-run the script.
// Row ids that are the place (the chosen row and same-named rows within 10 km) → the art file.
export const CN_BY_ID = {
${fmt(BY_ID)}
};
// Names the list and the database use for these places → the art file (each file maps to itself too).
export const CN_ALIAS = {
${fmt(ALIAS)}
};
// Only these rows may wear the file; a row elsewhere that merely shares the name never borrows it.
export const CN_ONLY = {
${fmt(ONLY, true)}
};
// And only inside China.
export const CN_CC = {
${fmt(CC, true)}
};
`;
fs.writeFileSync(OUT, out);
console.log(`wrote ${path.relative(ROOT, OUT)}: ${Object.keys(ONLY).length} files · ${Object.keys(BY_ID).length} row ids (${pendingRows} pending the SQL, ${extraRows} same-place extras) · ${Object.keys(ALIAS).length} aliases`);
