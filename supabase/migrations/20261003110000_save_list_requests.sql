  id         uuid primary key default gen_random_uuid(),
  user_id    uuid not null,
  email      text,
  kind       text not null,           -- 'username' | 'seal'
  handle     text,
  note       text,
  status     text not null default 'open',  -- open | done | dismissed
  created_at timestamptz default now(),
  resolved_at timestamptz
);
create index if not exists handle_requests_open_idx on api.handle_requests (status, created_at desc);
alter table api.handle_requests enable row level security;
